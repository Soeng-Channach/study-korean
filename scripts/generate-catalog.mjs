// Regenerates src/data/catalog.js — the small counts-only summary that the
// dashboard, progress page, and learning context read instead of importing the
// multi-megabyte datasets. Run `npm run catalog` after changing src/data.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

import { grammarLessons } from '../src/data/grammar.js';
import { listeningTests } from '../src/data/listening.js';
import { mockTests } from '../src/data/mockTests.js';
import { readings } from '../src/data/reading.js';
import { vocabulary } from '../src/data/vocabulary.js';
import { countByLevel } from '../src/lib/levels.js';

const SETS = {
  grammar: grammarLessons,
  vocabulary,
  reading: readings,
  listening: listeningTests,
  mockTests
};

const catalog = Object.fromEntries(
  Object.entries(SETS).map(([key, items]) => [
    key,
    { total: items.length, byLevel: countByLevel(items) }
  ])
);

const outPath = path.join(path.dirname(fileURLToPath(import.meta.url)), '../src/data/catalog.js');
const body = `// GENERATED by scripts/generate-catalog.mjs — do not edit by hand.
// Counts-only summary of src/data so that always-mounted code (app shell,
// dashboard, progress) can show totals without pulling in ~4 MB of content.
// Run \`npm run catalog\` after adding or removing content.
export const catalog = ${JSON.stringify(catalog, null, 2)};
`;

writeFileSync(outPath, body, 'utf8');
console.log(`wrote ${path.relative(process.cwd(), outPath)}`);

// List pages only need a few fields per test, so they read this small index
// instead of the full reading/listening datasets (~1 MB each). The full test
// is loaded only when a learner opens it.
const PREVIEW_LENGTH = 220;
function summarize(test) {
  const summary = {
    id: test.id,
    title: test.title,
    level: test.level,
    topic: test.topic,
    questionCount: test.questionCount || test.questions.length,
    durationMinutes: test.durationMinutes,
    paperSrc: test.paperSrc,
    passage: test.passage ? test.passage.slice(0, PREVIEW_LENGTH) : undefined
  };
  return Object.fromEntries(Object.entries(summary).filter(([, value]) => value !== undefined && value !== ''));
}

const indexPath = path.join(path.dirname(fileURLToPath(import.meta.url)), '../src/data/testIndex.js');
const indexBody = `// GENERATED by scripts/generate-catalog.mjs — do not edit by hand.
// Lightweight summaries of the reading and listening tests for list pages.
// Run \`npm run catalog\` after adding or removing content.
export const readingIndex = ${JSON.stringify(readings.map(summarize), null, 2)};

export const listeningIndex = ${JSON.stringify(listeningTests.map(summarize), null, 2)};
`;
writeFileSync(indexPath, indexBody, 'utf8');
console.log(`wrote ${path.relative(process.cwd(), indexPath)}`);
for (const [key, value] of Object.entries(catalog)) {
  console.log(`  ${key.padEnd(11)} ${String(value.total).padStart(5)}  ${JSON.stringify(value.byLevel)}`);
}
