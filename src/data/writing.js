// Characters as counted on the answer sheet: every character and space takes
// one square; line breaks do not count.
export function countCharacters(text) {
  return String(text || '').replace(/\r?\n/g, '').length;
}

// Sentence endings in the polite or spoken style (-요, -습니다/-ㅂ니다, -ㅂ니까),
// which lose points in Q53-54. "아니다" is plain style: only a syllable with a
// ㅂ final consonant before 니다/니까 (합니다, 입니다, 습니다) counts.
export function politeEndings(text) {
  const found = [];
  const pattern = /([가-힣]+)(?=\s*[.?!])/g;
  let match;
  while ((match = pattern.exec(String(text || '')))) {
    const word = match[1];
    const polite =
      /요$/.test(word) ||
      (/(니다|니까)$/.test(word) && word.length >= 3 && (word.charCodeAt(word.length - 3) - 0xac00) % 28 === 17);
    if (polite && !found.includes(word)) found.push(word);
  }
  return found;
}
