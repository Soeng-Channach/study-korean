const Q54_INSTRUCTION =
  '다음을 주제로 하여 자신의 생각을 600~700자로 글을 쓰십시오. 단, 문제를 그대로 옮겨 쓰지 마십시오. (50점)';

function blankQuestion(number, title, passage, blanks) {
  return { number, type: 'blank', points: 10, instruction: BLANK_INSTRUCTION, title, passage, blanks };
}

function chartQuestion(prompt, chart, model) {
  return { number: 53, type: 'chart', points: 30, min: 200, max: 300, instruction: Q53_INSTRUCTION, prompt, chart, model };
}

function essayQuestion(topic, intro, questions, model) {
  return { number: 54, type: 'essay', points: 50, min: 600, max: 700, instruction: Q54_INSTRUCTION, topic, intro, questions, model };
}

